export function localizeProject(project: Project, lang: "en" | "ar"): Project {
  if (lang !== "ar") return project;
  const overlay = projectsAr[project.slug];
  const mapped = overlay ? { ...project, ...overlay } : { ...project };
  const contentLangMap: Record<string, string> = { English: "إنجليزي", Arabic: "عربي" };
  return {
    ...mapped,
    contentLanguages: mapped.contentLanguages.map((item) => contentLangMap[item] ?? item)
  };
}
