import { caseStudiesAr } from "@/data/caseStudiesAr";
import type { Project } from "@/data/projects";

type ProjectAr = Partial<
  Pick<
    Project,
    | "title"
    | "description"
    | "type"
    | "period"
    | "longDescription"
    | "skillsUsed"
    | "responsibilities"
    | "highlights"
    | "features"
    | "contentLanguages"
  >
>;

function fromCaseStudy(slug: string, title: string, type: string, period: string): ProjectAr {
  const study = caseStudiesAr.find((item) => item.slug === slug);
  if (!study) throw new Error(`Missing Arabic case study: ${slug}`);
  return {
    title, type, period,
    description: study.tagline,
    longDescription: `${study.problem} ${study.role}`,
    responsibilities: [study.role],
    highlights: study.results,
    features: study.approach.map((step) => `${step.title}: ${step.body}`)
  };
}

